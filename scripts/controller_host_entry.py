"""Detached main-PC controller entry with exact-build and process containment guards.

Use only through a newly created, source-hashed per-run plan generated by the
on-demand controller prerequisite. stdout.private.log must not be published.
"""
from __future__ import annotations

import contextlib
import ctypes
from ctypes import wintypes
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import runpy
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main():
    if len(sys.argv) != 2:
        raise RuntimeError("exactly-one-plan-required")
    plan_path = Path(sys.argv[1]).resolve(strict=True)
    if plan_path.is_symlink() or plan_path.name != "plan.json":
        raise RuntimeError("invalid-plan-path")
    output = plan_path.parent
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    if plan.get("schemaVersion") != 1:
        raise RuntimeError("invalid-plan-version")
    with (output / "stdout.private.log").open("x", encoding="utf-8", buffering=1) as stdout, \
         (output / "stderr.log").open("x", encoding="utf-8", buffering=1) as stderr, \
         contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
        from scripts.vm_console_native import process_identity
        from scripts.control_host import HostConfig, VmEpochGuard
        try:
            for relative, digest in plan["runtimeHashes"].items():
                part = Path(relative)
                if part.is_absolute() or ".." in part.parts:
                    raise RuntimeError("invalid-runtime-source-path")
                target = ROOT / part
                if target.is_symlink() or not target.resolve().is_relative_to(ROOT.resolve()) \
                   or sha(target) != digest:
                    raise RuntimeError("runtime-hash-changed")
            config_path = Path(plan["configPath"]).resolve(strict=True)
            if sha(config_path) != plan["configSha256"]:
                raise RuntimeError("config-hash-changed")
            identity = VmEpochGuard(HostConfig.load(config_path)).collect()
            if identity != plan["vmIdentity"]:
                raise RuntimeError("vm-epoch-changed")
            api = ctypes.WinDLL("kernel32", use_last_error=True)
            api.GetCurrentProcess.restype = wintypes.HANDLE
            api.IsProcessInJob.argtypes = [wintypes.HANDLE, wintypes.HANDLE,
                                           ctypes.POINTER(wintypes.BOOL)]
            session, job = wintypes.DWORD(), wintypes.BOOL()
            if not api.ProcessIdToSessionId(os.getpid(), ctypes.byref(session)) \
               or not api.IsProcessInJob(api.GetCurrentProcess(), None, ctypes.byref(job)):
                raise RuntimeError("containment-query-failed")
            if session.value != plan["expectedWindowsSession"] or job.value:
                raise RuntimeError("unexpected-process-containment")
            with (output / "process.json").open("x", encoding="utf-8") as receipt:
                json.dump({"pid": os.getpid(),
                           "processIdentity": process_identity(os.getpid()),
                           "windowsSessionId": session.value, "inJob": bool(job.value),
                           "vmIdentity": identity, "configSha256": plan["configSha256"],
                           "runtimeHashes": plan["runtimeHashes"],
                           "canonicalDatabase": plan["database"],
                           "resource": plan["resource"],
                           "atUtc": datetime.now(timezone.utc).isoformat()},
                          receipt, indent=2)
            source = ROOT / "scripts/control_host.py"
            sys.argv = [str(source), "--config", str(config_path),
                        "--coordination-db", plan["database"],
                        "--coordination-resource", plan["resource"],
                        "--reconcile-existing", "--shutdown-file", plan["shutdownFile"]]
            try:
                runpy.run_path(str(source), run_name="__main__")
            finally:
                with (output / "exited.json").open("x", encoding="utf-8") as receipt:
                    json.dump({"pid": os.getpid(),
                               "atUtc": datetime.now(timezone.utc).isoformat()}, receipt)
        except Exception as error:
            # Error class/code only, no tokens, config or private source data.
            with (output / "failure.json").open("x", encoding="utf-8") as receipt:
                json.dump({"type": type(error).__name__,
                           "code": (str(error) if str(error) in {
                               "runtime-hash-changed", "config-hash-changed",
                               "vm-epoch-changed", "containment-query-failed",
                               "unexpected-process-containment",
                               "invalid-runtime-source-path"
                           } else "startup-failed")}, receipt)
            raise


if __name__ == "__main__":
    main()
